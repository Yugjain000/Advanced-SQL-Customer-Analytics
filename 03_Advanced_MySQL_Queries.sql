-- ------------------------------------------------------------------------------
-- QUERY 1: RFM (Recency, Frequency, Monetary) Customer Segmentation
-- Business Value: Classifies customers into actionable marketing segments.
-- Advanced Concepts: Common Table Expressions (CTEs), NTILE() Window Function, Aggregations.
-- ------------------------------------------------------------------------------
WITH CustomerStats AS (
    SELECT 
        c.customer_id,
        c.first_name,
        c.last_name,
        MAX(o.order_date) AS last_purchase_date,
        COUNT(DISTINCT o.order_id) AS total_orders,
        SUM(oi.quantity * oi.unit_price) AS total_spent
    FROM customers c
    JOIN orders o ON c.customer_id = o.customer_id
    JOIN order_items oi ON o.order_id = oi.order_id
    WHERE o.status = 'Completed'
    GROUP BY c.customer_id, c.first_name, c.last_name
),
RFMScores AS (
    SELECT 
        customer_id,
        first_name,
        last_name,
        DATEDIFF(CURRENT_DATE, last_purchase_date) AS recency_days,
        total_orders AS frequency,
        total_spent AS monetary,
        -- Divide customers into 4 quartiles for each metric
        NTILE(4) OVER (ORDER BY DATEDIFF(CURRENT_DATE, last_purchase_date) DESC) AS R_Score,
        NTILE(4) OVER (ORDER BY total_orders ASC) AS F_Score,
        NTILE(4) OVER (ORDER BY total_spent ASC) AS M_Score
    FROM CustomerStats
)
SELECT 
    customer_id,
    first_name,
    last_name,
    recency_days,
    frequency,
    monetary,
    CONCAT(R_Score, F_Score, M_Score) AS RFM_Cell,
    CASE 
        WHEN R_Score >= 3 AND F_Score >= 3 AND M_Score >= 3 THEN 'Champions'
        WHEN R_Score >= 2 AND F_Score >= 3 THEN 'Loyal Customers'
        WHEN R_Score <= 2 AND F_Score <= 2 THEN 'At Risk / Churning'
        WHEN R_Score = 1 THEN 'Lost Customers'
        ELSE 'Potential'
    END AS Customer_Segment
FROM RFMScores
ORDER BY M_Score DESC, F_Score DESC;


-- ------------------------------------------------------------------------------
-- QUERY 2: E-Commerce Funnel Drop-off Analysis
-- Business Value: Identifies the exact step where users abandon the website.
-- Advanced Concepts: LEAD(), LAG(), Subqueries, Sessionization.
-- ------------------------------------------------------------------------------
WITH EventPaths AS (
    SELECT 
        customer_id,
        event_type,
        event_timestamp,
        -- Look at the NEXT event the user triggered
        LEAD(event_type) OVER(PARTITION BY customer_id ORDER BY event_timestamp) as next_event,
        -- Calculate time difference between steps in minutes
        TIMESTAMPDIFF(MINUTE, event_timestamp, LEAD(event_timestamp) OVER(PARTITION BY customer_id ORDER BY event_timestamp)) as minutes_to_next_step
    FROM user_events
)
SELECT 
    event_type AS current_step,
    next_event AS next_step,
    COUNT(*) AS transition_count,
    ROUND(AVG(minutes_to_next_step), 2) AS avg_minutes_between_steps
FROM EventPaths
WHERE next_event IS NOT NULL
GROUP BY event_type, next_event
ORDER BY transition_count DESC;


-- ------------------------------------------------------------------------------
-- QUERY 3: Recursive Employee Sales Hierarchy (Manager -> Employee -> Sales)
-- Business Value: Shows total sales generated by a manager's entire team (including indirect reports).
-- Advanced Concepts: Recursive CTEs (WITH RECURSIVE)
-- ------------------------------------------------------------------------------
WITH RECURSIVE SalesHierarchy AS (
    -- Anchor member: Select the top managers (e.g., CEO, who has no manager)
    SELECT 
        employee_id, 
        first_name, 
        last_name, 
        manager_id,
        1 AS hierarchy_level
    FROM employees
    WHERE manager_id IS NULL
    
    UNION ALL
    
    -- Recursive member: Join employees to their managers
    SELECT 
        e.employee_id, 
        e.first_name, 
        e.last_name, 
        e.manager_id,
        sh.hierarchy_level + 1
    FROM employees e
    INNER JOIN SalesHierarchy sh ON e.manager_id = sh.employee_id
),
EmployeeSales AS (
    SELECT 
        e.employee_id,
        SUM(oi.quantity * oi.unit_price) AS direct_sales
    FROM employees e
    LEFT JOIN orders o ON e.employee_id = o.employee_id
    LEFT JOIN order_items oi ON o.order_id = oi.order_id
    GROUP BY e.employee_id
)
SELECT 
    sh.hierarchy_level,
    sh.first_name AS employee_name,
    COALESCE(es.direct_sales, 0) AS direct_sales_generated
FROM SalesHierarchy sh
LEFT JOIN EmployeeSales es ON sh.employee_id = es.employee_id
ORDER BY sh.hierarchy_level, direct_sales_generated DESC;
